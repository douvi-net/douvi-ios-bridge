import type { BuildEngineAdapter, WorkflowConfig } from "./types";

export const actionPins = {
  checkout: "fbc6f3992d24b796d5a048ff273f7fcc4a7b6c09",
  flutter: "1a449444c387b1966244ae4d4f8c696479add0b2",
  uploadArtifact: "ea165f8d65b6e75b540449e92b4886f43607fa02",
} as const;

export function validateWorkflowConfig(config: WorkflowConfig): void {
  if (config.mode !== "unsigned")
    throw new Error(
      "Signed IPA workflows are unavailable until signing integration and verification are implemented.",
    );
  if (!/^\d{1,3}\.\d{1,3}\.\d{1,3}$/.test(config.flutterVersion))
    throw new Error("Pin an exact stable Flutter version, for example 3.38.5.");
  if (
    config.projectDirectory !== "." &&
    (!/^[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_.-]+)*$/.test(config.projectDirectory) ||
      config.projectDirectory.split("/").some((s) => s === "." || s === ".."))
  )
    throw new Error(
      "Use a safe project-relative directory without traversal, spaces or expressions.",
    );
  if (!["macos-15", "macos-26"].includes(config.runner))
    throw new Error("Only standard macOS runner labels are supported.");
  if (
    !Number.isInteger(config.timeoutMinutes) ||
    config.timeoutMinutes < 5 ||
    config.timeoutMinutes > 60
  )
    throw new Error("Build timeout must be 5–60 minutes.");
  if (
    !Number.isInteger(config.retentionDays) ||
    config.retentionDays < 1 ||
    config.retentionDays > 7
  )
    throw new Error("Artifact retention must be 1–7 days.");
}

/** Produces a draft only. No disk writes, upload, API call or workflow dispatch. */
export function generateUnsignedWorkflow(config: WorkflowConfig): string {
  validateWorkflowConfig(config);
  const lines = [
    "# Generated by Douvi iOS Bridge. Review before saving or running.",
    "# This lane produces an UNSIGNED .app ZIP, not an installable signed IPA.",
    "name: Bridge · Flutter iOS unsigned",
    "run-name: Unsigned Flutter iOS · ${{ inputs.reviewed_commit }}",
    "on:",
    "  workflow_dispatch:",
    "    inputs:",
    "      reviewed_commit:",
    "        description: Exact 40-character source commit SHA you reviewed",
    "        required: true",
    "        type: string",
    "      confirm_ci_cost:",
    "        description: I reviewed account quota, runner cost and artifact storage",
    "        required: true",
    "        type: boolean",
    "        default: false",
    "      confirm_source_execution:",
    "        description: I trust this commit and its dependency build scripts",
    "        required: true",
    "        type: boolean",
    "        default: false",
    "permissions:",
    "  contents: read",
    "concurrency:",
    "  group: bridge-unsigned-${{ github.ref }}",
    "  cancel-in-progress: false",
    "jobs:",
    "  build:",
    "    if: ${{ inputs.confirm_ci_cost && inputs.confirm_source_execution }}",
    `    runs-on: ${config.runner}`,
    `    timeout-minutes: ${config.timeoutMinutes}`,
    "    env:",
    `      BRIDGE_PROJECT_DIR: ${JSON.stringify(config.projectDirectory)}`,
    "      REVIEWED_COMMIT: ${{ inputs.reviewed_commit }}",
    "    steps:",
    "      - name: Validate reviewed commit",
    "        shell: bash",
    "        run: |",
    "          python3 - <<'PY'",
    "          import os, re",
    "          if not re.fullmatch(r'[a-fA-F0-9]{40}', os.environ['REVIEWED_COMMIT']):",
    "              raise SystemExit('A full reviewed source commit SHA is required.')",
    "          PY",
    `      - uses: actions/checkout@${actionPins.checkout} # v5, verified 2026-11-03`,
    "        with:",
    "          ref: ${{ inputs.reviewed_commit }}",
    "          persist-credentials: false",
    "      - name: Validate project boundary",
    "        shell: bash",
    "        run: |",
    "          python3 - <<'PY'",
    "          import os, pathlib",
    "          root = pathlib.Path(os.environ['GITHUB_WORKSPACE']).resolve()",
    "          project = (root / os.environ['BRIDGE_PROJECT_DIR']).resolve()",
    "          if not project.is_relative_to(root) or not (project / 'pubspec.yaml').is_file():",
    "              raise SystemExit('Project must be inside the checkout and contain pubspec.yaml.')",
    "          PY",
    `      - uses: subosito/flutter-action@${actionPins.flutter} # v2, cache disabled`,
    "        with:",
    `          flutter-version: ${JSON.stringify(config.flutterVersion)}`,
    "          channel: stable",
    "          cache: false",
    "      - name: Build unsigned iOS app",
    "        shell: bash",
    "        run: |",
    "          set -euo pipefail",
    '          cd -- "$BRIDGE_PROJECT_DIR"',
    "          flutter --version",
    "          xcodebuild -version",
    "          flutter pub get",
    "          flutter build ios --release --no-codesign",
    "      - name: Validate and package actual build output",
    "        shell: bash",
    "        run: |",
    "          set -euo pipefail",
    '          cd -- "$BRIDGE_PROJECT_DIR"',
    "          python3 - <<'PY'",
    "          import pathlib, plistlib, subprocess",
    "          apps = list(pathlib.Path('build/ios/iphoneos').glob('*.app'))",
    "          if len(apps) != 1: raise SystemExit('Expected exactly one built app.')",
    "          app = apps[0]",
    "          info = plistlib.loads((app / 'Info.plist').read_bytes())",
    "          exe = app / info.get('CFBundleExecutable', '')",
    "          if not exe.is_file() or exe.stat().st_size == 0: raise SystemExit('App executable missing.')",
    "          description = subprocess.check_output(['file', str(exe)], text=True)",
    "          if 'Mach-O' not in description or 'arm64' not in description: raise SystemExit('Expected iOS arm64 Mach-O.')",
    "          subprocess.run(['ditto', '-c', '-k', '--sequesterRsrc', '--keepParent', str(app), 'unsigned-ios-app.zip'], check=True)",
    "          PY",
    "          shasum -a 256 unsigned-ios-app.zip > unsigned-ios-app.zip.sha256",
    `      - uses: actions/upload-artifact@${actionPins.uploadArtifact} # v4`,
    "        with:",
    "          name: unsigned-ios-app-${{ github.run_id }}",
    "          path: |",
    `            ${config.projectDirectory}/unsigned-ios-app.zip`,
    `            ${config.projectDirectory}/unsigned-ios-app.zip.sha256`,
    "          if-no-files-found: error",
    `          retention-days: ${config.retentionDays}`,
    "",
  ];
  return lines.join("\n");
}

